"""Refresh the catalogue index from the explicit populated options."""

from pathlib import Path

import working_populate


def main():
    rows = []
    rows.append("# Timing pulley catalogue\n")
    rows.append("Generated by `python action_documentation.py` from `working_populate.get_options()`.\n")
    rows.append("Depth is nominal belt width. Diameter is an OOBB catalogue grid size.\n")
    rows.append("M3/M6 counts are additional through holes per assembled pulley; the central bore and joining/coupler fasteners are separate.\n")
    rows.append("| Teeth | Belt mm | Style | Bore mm | M3 holes | M6 holes | Files |")
    rows.append("| ---: | ---: | --- | ---: | ---: | ---: | --- |")
    for option in working_populate.get_options():
        folder = "parts/" + option["id"]
        bore = option.get("coupler_bore", "")
        files = f"[YAML]({folder}/working.yaml) · [print SCAD]({folder}/3dpr.scad) · [STL]({folder}/3dpr.stl) · [assembly]({folder}/true.scad)"
        if "coupler" in option:
            files += f" · [metal assembly]({folder}/assembly_with_coupler.scad)"
        holes = option["assembled_dimensions"]["oobb_hole_positions"]
        m3_count = sum(hole["radius_name"] == "m3" for hole in holes)
        m6_count = sum(hole["radius_name"] == "m6" for hole in holes)
        rows.append(f"| {option['number_of_teeth']} | {option['depth']} | {option['style']} | {bore} | {m3_count} | {m6_count} | {files} |")
    Path("catalogue.md").write_text("\n".join(rows) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
